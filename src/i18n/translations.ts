export type TranslationKey = keyof typeof TRANSLATIONS.id;

export function getTranslation(lang: Language, key: TranslationKey | string, defaultText?: string): string {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.id;
  const translated = (dictionary as Record<string, string>)[key];
  if (translated) return translated;
  if (defaultText !== undefined) return defaultText;
  // Fallback to Indonesian then English then key
  return TRANSLATIONS.id[key as TranslationKey] || TRANSLATIONS.en[key as TranslationKey] || key;
}
